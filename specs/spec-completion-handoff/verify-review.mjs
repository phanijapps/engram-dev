import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { loadPackWithMeta, planDigest, evidenceDigest, currentReview } from '../../treadle/packages/core/dist/src/specpack/index.js';
const dir = dirname(fileURLToPath(import.meta.url));
const loaded = loadPackWithMeta(dir); assert.ok(loaded.ok, loaded.message);
const {doc,path} = loaded.value;
const scope = planDigest(doc,path); assert.ok(scope.ok, scope.message);
assert.ok(currentReview(doc,scope.value), 'Current independent PACK PASS required');
const verdict = doc.review.verdicts.filter(v=>v.on==='PACK').at(-1);
assert.equal(verdict.by, 'agent:replay_review');
assert.equal(verdict.evidence_digest,evidenceDigest(doc));
const artifact = doc.artifacts.delivery_review;
assert.ok(artifact?.file && artifact.sha256, 'Independent review artifact and observed hash required');
const body = readFileSync(resolve(dir,artifact.file));
assert.equal(createHash('sha256').update(body).digest('hex'),artifact.sha256);
assert.ok(doc.tasks.filter(t=>t.phase!=='review').every(t=>t.status==='done' && t.evidence?.at(-1)?.exit===0), 'Implementation tasks must be checked');
console.log('Independent review matches this plan, current task evidence and the preserved review artifact. Owner completion remains separate.');
